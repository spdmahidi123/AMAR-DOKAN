-- 1. EXTENSIONS & ENUMS
CREATE EXTENSION IF NOT EXISTS "uuid-ossp";

CREATE TYPE order_status_enum AS ENUM (
    'NEW',
    'CONFIRMED',
    'PROCESSING',
    'SHIPPED',
    'DELIVERED',
    'CANCELLED'
);

CREATE TYPE payment_status_enum AS ENUM (
    'UNPAID',
    'PAID'
);

-- 2. ADMIN PROFILES TABLE (Linked with Supabase Auth)
CREATE TABLE IF NOT EXISTS public.admin_profiles (
    id UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
    email TEXT NOT NULL,
    full_name TEXT NOT NULL,
    role TEXT NOT NULL DEFAULT 'admin' CHECK (role IN ('super_admin', 'admin', 'moderator')),
    created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 3. CATEGORIES TABLE
CREATE TABLE IF NOT EXISTS public.categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name_bn TEXT NOT NULL,
    name_en TEXT NOT NULL,
    icon_name TEXT DEFAULT 'store',
    display_order INT DEFAULT 0,
    created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 4. PRODUCTS & INVENTORY TABLE
CREATE TABLE IF NOT EXISTS public.products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title_bn TEXT NOT NULL,
    title_en TEXT NOT NULL,
    description_bn TEXT NOT NULL,
    description_en TEXT NOT NULL,
    category_id BIGINT REFERENCES public.categories(id) ON DELETE SET NULL,
    category_bn TEXT NOT NULL,
    category_en TEXT NOT NULL,
    sku TEXT UNIQUE NOT NULL,
    purchase_cost NUMERIC(12, 2) NOT NULL CHECK (purchase_cost >= 0),
    selling_price NUMERIC(12, 2) NOT NULL CHECK (selling_price >= 0),
    discount_price NUMERIC(12, 2) CHECK (discount_price IS NULL OR discount_price >= 0),
    stock_quantity INT NOT NULL DEFAULT 0 CHECK (stock_quantity >= 0),
    low_stock_threshold INT NOT NULL DEFAULT 5 CHECK (low_stock_threshold >= 0),
    is_featured BOOLEAN DEFAULT false NOT NULL,
    is_active BOOLEAN DEFAULT true NOT NULL,
    image_url TEXT DEFAULT '',
    created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

CREATE INDEX idx_products_sku ON public.products(sku);
CREATE INDEX idx_products_active ON public.products(is_active);

-- 5. ORDERS TABLE
CREATE TABLE IF NOT EXISTS public.orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_number TEXT UNIQUE NOT NULL,
    customer_id UUID REFERENCES auth.users(id) ON DELETE SET NULL,
    customer_name TEXT NOT NULL,
    phone TEXT NOT NULL,
    delivery_address TEXT NOT NULL,
    district TEXT NOT NULL,
    area TEXT NOT NULL,
    order_notes TEXT DEFAULT '',
    subtotal NUMERIC(12, 2) NOT NULL CHECK (subtotal >= 0),
    delivery_charge NUMERIC(12, 2) NOT NULL CHECK (delivery_charge >= 0),
    discount NUMERIC(12, 2) DEFAULT 0 CHECK (discount >= 0),
    total_amount NUMERIC(12, 2) NOT NULL CHECK (total_amount >= 0),
    payment_method TEXT DEFAULT 'ক্যাশ অন ডেলিভারি (COD)' NOT NULL,
    payment_status payment_status_enum DEFAULT 'UNPAID' NOT NULL,
    order_status order_status_enum DEFAULT 'NEW' NOT NULL,
    is_acknowledged BOOLEAN DEFAULT false NOT NULL,
    created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

CREATE INDEX idx_orders_number ON public.orders(order_number);
CREATE INDEX idx_orders_created_at ON public.orders(created_at DESC);
CREATE INDEX idx_orders_status ON public.orders(order_status);

-- 6. ORDER ITEMS TABLE (Capturing historical purchase & selling price snapshot)
CREATE TABLE IF NOT EXISTS public.order_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT REFERENCES public.orders(id) ON DELETE CASCADE NOT NULL,
    product_id BIGINT REFERENCES public.products(id) ON DELETE RESTRICT NOT NULL,
    product_name_bn TEXT NOT NULL,
    product_name_en TEXT NOT NULL,
    sku TEXT NOT NULL,
    purchase_cost NUMERIC(12, 2) NOT NULL,
    selling_price NUMERIC(12, 2) NOT NULL,
    quantity INT NOT NULL CHECK (quantity > 0),
    line_total NUMERIC(12, 2) NOT NULL
);

CREATE INDEX idx_order_items_order_id ON public.order_items(order_id);

-- 7. INVENTORY AUDIT MOVEMENTS TABLE
CREATE TABLE IF NOT EXISTS public.inventory_movements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT REFERENCES public.products(id) ON DELETE CASCADE NOT NULL,
    product_name TEXT NOT NULL,
    change_quantity INT NOT NULL, -- e.g. -2 or +20
    previous_stock INT NOT NULL,
    new_stock INT NOT NULL,
    reason TEXT NOT NULL,
    admin_name TEXT DEFAULT 'Admin' NOT NULL,
    created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

CREATE INDEX idx_inventory_movements_prod ON public.inventory_movements(product_id);

-- 8. BUSINESS SETTINGS TABLE
CREATE TABLE IF NOT EXISTS public.business_settings (
    id INT PRIMARY KEY DEFAULT 1,
    store_name_bn TEXT DEFAULT 'আমার দোকান' NOT NULL,
    store_name_en TEXT DEFAULT 'Amar Dokan' NOT NULL,
    inside_dhaka_delivery_fee NUMERIC(10, 2) DEFAULT 60.00 NOT NULL,
    outside_dhaka_delivery_fee NUMERIC(10, 2) DEFAULT 120.00 NOT NULL,
    admin_email TEXT DEFAULT 'admin@amardokan.com.bd' NOT NULL,
    email_notifications_enabled BOOLEAN DEFAULT true NOT NULL,
    sound_alerts_enabled BOOLEAN DEFAULT true NOT NULL,
    updated_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 9. NOTIFICATION LOGS
CREATE TABLE IF NOT EXISTS public.notification_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT REFERENCES public.orders(id) ON DELETE CASCADE,
    order_number TEXT NOT NULL,
    recipient_email TEXT NOT NULL,
    subject TEXT NOT NULL,
    message_body TEXT NOT NULL,
    status TEXT DEFAULT 'SENT' NOT NULL,
    created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

