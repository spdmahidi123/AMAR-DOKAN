-- Helper function to check if current user is an authenticated Admin
CREATE OR REPLACE FUNCTION public.is_admin()
RETURNS BOOLEAN AS $$
BEGIN
    RETURN EXISTS (
        SELECT 1 FROM public.admin_profiles
        WHERE id = auth.uid() AND role IN ('admin', 'super_admin')
    );
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- Products RLS:
-- Public visitors can read active products only
CREATE POLICY "Public can view active products"
ON public.products FOR SELECT
USING (is_active = true);

-- Admins can view and manage all products
CREATE POLICY "Admins can manage products"
ON public.products FOR ALL
USING (public.is_admin());

-- Categories RLS:
CREATE POLICY "Public can view categories"
ON public.categories FOR SELECT
USING (true);

CREATE POLICY "Admins can manage categories"
ON public.categories FOR ALL
USING (public.is_admin());

-- Orders RLS:
-- Anonymous/customers can insert orders (checkout)
CREATE POLICY "Anyone can place order"
ON public.orders FOR INSERT
WITH CHECK (true);

-- Customers can view their own orders if authenticated
CREATE POLICY "Customers view own orders"
ON public.orders FOR SELECT
USING (customer_id = auth.uid() OR public.is_admin());

-- Only admins can update order statuses or delete orders
CREATE POLICY "Admins manage orders"
ON public.orders FOR ALL
USING (public.is_admin());

-- Order Items RLS:
CREATE POLICY "Anyone can insert order items"
ON public.order_items FOR INSERT
WITH CHECK (true);

CREATE POLICY "View order items"
ON public.order_items FOR SELECT
USING (
    EXISTS (
        SELECT 1 FROM public.orders
        WHERE orders.id = order_items.order_id
        AND (orders.customer_id = auth.uid() OR public.is_admin())
    )
);

-- Inventory movements RLS: Only admins
CREATE POLICY "Admins view and manage inventory movements"
ON public.inventory_movements FOR ALL
USING (public.is_admin());

-- Business settings: Public can read, only admin can update
CREATE POLICY "Public read business settings"
ON public.business_settings FOR SELECT
USING (true);

CREATE POLICY "Admins manage business settings"
ON public.business_settings FOR ALL
USING (public.is_admin());

